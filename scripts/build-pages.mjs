import { spawnSync } from 'node:child_process';
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const generatedMarker = '// Generated by scripts/build-pages.mjs; do not edit.\n';
const pagesConfigPath = path.join(root, 'wrangler.jsonc');
// The Vite plugin builds a Worker first. Expose the Pages configuration only
// afterwards, so it cannot be mistaken for a Worker input on subsequent builds.
try {
  const previous = await readFile(pagesConfigPath, 'utf8');
  if (!previous.startsWith(generatedMarker)) {
    throw new Error('An existing wrangler.jsonc is not owned by this Pages build. Preserve it and resolve the configuration before continuing.');
  }
  await rm(pagesConfigPath);
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
const built = spawnSync(process.execPath, [path.join(root, 'scripts/run-framework.mjs'), 'build'], {
  cwd: root,
  stdio: 'inherit',
});
if (built.error) throw built.error;
if (built.status !== 0) process.exit(built.status ?? 1);

const server = path.join(root, 'dist/server');
const client = path.join(root, 'dist/client');
await readFile(path.join(server, 'index.js'));
const output = path.join(root, 'dist/pages');
if (path.dirname(output) !== path.join(root, 'dist')) throw new Error('Unexpected output path');
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await cp(client, output, { recursive: true });
const privateWorker = path.join(output, '_worker.js');
await mkdir(privateWorker, { recursive: true });
await cp(server, path.join(privateWorker, 'server'), {
  recursive: true,
  filter: (source) => !/\.(?:map|json)$/.test(source) && !['BUILD_ID', '.vite'].includes(path.basename(source)),
});

const staticEntries = await readdir(client, { withFileTypes: true });
const publicPaths = staticEntries.filter((entry) => !entry.isDirectory() && !entry.name.startsWith('_')).map((entry) => '/' + entry.name);
const publicPrefixes = staticEntries.filter((entry) => entry.isDirectory() && entry.name !== '_next' && !entry.name.startsWith('.')).map((entry) => '/' + entry.name + '/');
publicPrefixes.push('/_next/static/');
const worker = `import app from './server/index.js';
const paths = new Set(${JSON.stringify(publicPaths)});
const prefixes = ${JSON.stringify(publicPrefixes)};
export default {
  fetch(request, env, ctx) {
    const pathname = new URL(request.url).pathname;
    if ((request.method === 'GET' || request.method === 'HEAD') &&
        (paths.has(pathname) || prefixes.some(prefix => pathname.startsWith(prefix)))) {
      return env.ASSETS.fetch(request);
    }
    return app.fetch(request, env, ctx);
  }
};
`;
await writeFile(path.join(privateWorker, 'index.js'), worker);
await writeFile(path.join(output, '_routes.json'), JSON.stringify({
  version: 1,
  include: ['/*'],
  exclude: [...publicPaths, ...publicPrefixes.map((prefix) => prefix + '*')],
}, null, 2) + '\n');

const databaseSettings = JSON.parse(await readFile(path.join(root, 'cloudflare-d1.json'), 'utf8'));
// Preview deployments must opt into a separate database; they never inherit production learning data.
const isPreview = process.env.CF_PAGES === '1' && process.env.CF_PAGES_BRANCH !== 'main';
const databaseId = isPreview ? process.env.READSPACE_PREVIEW_D1_DATABASE_ID : process.env.READSPACE_D1_DATABASE_ID || databaseSettings.database_id;
if (databaseId && !/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(databaseId)) throw new Error('READSPACE_D1_DATABASE_ID must be a D1 database UUID.');
await writeFile(pagesConfigPath, generatedMarker + JSON.stringify({
  $schema: './node_modules/wrangler/config-schema.json',
  name: 'reading-space',
  pages_build_output_dir: './dist/pages',
  compatibility_date: '2026-05-15',
  compatibility_flags: ['nodejs_compat'],
  ...(databaseId ? { d1_databases: [{ binding: 'READSPACE_DB', database_name: isPreview ? 'readspace-accounts-preview' : databaseSettings.database_name, database_id: databaseId }] } : {}),
}, null, 2) + '\n');
// Replace only Vite's generated deployment redirect, never a source manifest.
const redirect = path.join(root, '.wrangler/deploy/config.json');
await mkdir(path.dirname(redirect), { recursive: true });
await writeFile(redirect, JSON.stringify({ configPath: '../../wrangler.jsonc' }) + '\n');
console.log('Pages build ready: dist/pages (server-side rendering + API routes + static assets).');
